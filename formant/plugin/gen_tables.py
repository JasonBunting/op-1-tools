"""Write fm_tables.h: vowel formants for the formant engine, taken from CHIMERA's vowel targets.

    python gen_tables.py <chimera>/crates/chimera/src/phonetics/vowelTargets.generated.json

CHIMERA (https://github.com/jamesondh/chimera-vocal-synth, MIT, Copyright (c) 2026 Jameson Hodge) fits its vocal
tract to each vowel and records the formants its model then produces, for a male, female and child body. This takes
F1..F4 of the vowels on the blue knob's path. Where a body has no F4 it is scaled from the next larger body by the
F3 ratio. F5 is F4 * 1.18 (not in CHIMERA's data).
"""
import json
import sys
from pathlib import Path

PATH = ["i", "ɪ", "e", "ɛ", "æ", "ɑ", "ɔ", "o", "u"]   # blue: front close ("ee") .. back close ("oo")
WORDS = ["heed", "hid", "hayed", "head", "had", "hod", "hawed", "hoed", "who'd"]
BODIES = ["male", "female", "child"]                    # green: left .. right


def main():
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    rows = {}
    for b in BODIES:
        rows[b] = []
        for v in PATH:
            f = list(data[b][v]["formants"])
            if len(f) < 4:
                bigger = rows[BODIES[BODIES.index(b) - 1]][PATH.index(v)]
                f.append(round(bigger[3] * f[2] / bigger[2]))
            f = f[:4] + [round(f[3] * 1.18)]
            rows[b].append(f)
    out = ["/* Generated by gen_tables.py from CHIMERA's vowelTargets.generated.json; do not edit.",
           " * CHIMERA: https://github.com/jamesondh/chimera-vocal-synth, MIT, Copyright (c) 2026 Jameson Hodge. */",
           "#ifndef FM_TABLES_H", "#define FM_TABLES_H", "#include <stdint.h>", "",
           f"#define FM_VOWELS {len(PATH)}", f"#define FM_BODIES {len(BODIES)}", "#define FM_FORMANTS 5", "",
           "/* F1..F5 in Hz, [body: male, female, child][vowel] */",
           "static const uint16_t fm_formants[FM_BODIES][FM_VOWELS][FM_FORMANTS] = {"]
    for b in BODIES:
        out.append(f"    {{   /* {b} */")
        for v, w, f in zip(PATH, WORDS, rows[b]):
            out.append(f"        {{ {', '.join(f'{x:4d}' for x in f)} }},   /* {v} {w} */")
        out.append("    },")
    out += ["};", "#endif", ""]
    Path(__file__).with_name("fm_tables.h").write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
