/* Fits fm_levels.h: measures every body and vowel (no talk, no breath, no vibrato, full velocity) at three pitches
 * and writes the gains that bring each to the quietest one's loudness. Run it twice (the second pass refines).
 *   gcc -O2 -Wall -I mouth/plugin mouth/plugin/test/level_fit.c -lm -o /tmp/fm_fit && /tmp/fm_fit mouth/plugin/fm_levels.h
 * Copyright (C) 2026 Jason Bunting. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE). */
#include <math.h>
#include <stdio.h>
#include <string.h>
#include "fm_dsp.h"

static int16_t sine[8192];

static double rms_of(int32_t vowel15, int32_t body15)
{
    static const double pitch[3] = { 110, 220, 440 };
    double acc = 0; long n = 0;
    for (int p = 0; p < 3; p++) {
        fm_voice v;
        memset(&v, 0, sizeof v);
        fm_voice_reset(&v);
        int32_t inc[128];
        int16_t buf[128];
        for (int i = 0; i < 128; i++) inc[i] = (int32_t)(uint32_t)(pitch[p] / FM_RATE * 4294967296.0);
        fm_knobs k;
        fm_knobs_make(&k, vowel15, body15, 0, 0, 32767);
        fm_track(&k, (uint32_t)inc[0]);
        for (int b = 0; b < 600; b++) {
            fm_render(&v, &k, inc, 128, (1024 * k.level) >> 15, buf, sine);   /* the current table applied; low: never clips */
            if (b >= 150) for (int i = 0; i < 128; i++) { acc += (double)buf[i] * buf[i]; n++; }
        }
    }
    return sqrt(acc / n);
}

int main(int argc, char **argv)
{
    if (argc != 2) { fprintf(stderr, "usage: level_fit OUT.h\n"); return 2; }
    for (int i = 0; i < 8192; i++) sine[i] = (int16_t)lrint(32767.0 * sin(2 * M_PI * i / 8192.0));
    static const int32_t body_at[FM_BODIES] = { 5461, 16384, 27307 };   /* the man, the woman, the child exactly */
    double r[FM_BODIES][FM_VOWELS], lo = 1e9;
    for (int b = 0; b < FM_BODIES; b++)
        for (int v = 0; v < FM_VOWELS; v++) {
            r[b][v] = rms_of(v * 32767 / (FM_VOWELS - 1), body_at[b]) / (fm_levels[b][v] / 32767.0);   /* without the current gain */
            if (r[b][v] < lo) lo = r[b][v];
        }
    FILE *f = fopen(argv[1], "w");
    if (!f) { perror(argv[1]); return 1; }
    fprintf(f, "/* Generated by test/level_fit.c; do not edit. Loudness evening per body and vowel (Q15, applied as a gain). */\n"
               "#ifndef FM_LEVELS_H\n#define FM_LEVELS_H\n#include <stdint.h>\n"
               "static const int16_t fm_levels[FM_BODIES][FM_VOWELS] = {\n");
    for (int b = 0; b < FM_BODIES; b++) {
        fprintf(f, "    {");
        for (int v = 0; v < FM_VOWELS; v++) fprintf(f, " %5d%s", (int)lrint(32767.0 * lo / r[b][v]), v < FM_VOWELS - 1 ? "," : "");
        fprintf(f, " },   /* %s; unevened rms %.0f .. %.0f */\n", b == 0 ? "man" : b == 1 ? "woman" : "child",
                r[b][0], r[b][FM_VOWELS - 1]);
    }
    fprintf(f, "};\n#endif\n");
    fclose(f);
    printf("quietest %.0f; wrote %s\n", lo, argv[1]);
    return 0;
}
