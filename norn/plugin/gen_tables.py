#!/usr/bin/env python3
"""Writes the tables from Plaits' resources.cc. No numpy: it reads the numbers out of the C source.
1. ws_tables.h: the five waveshaper curves (already int16) and the wavefolder curve (float, converted to Q15).
2. fm_tables.h: the FM ratio quantizer as frequency multipliers (129 points, Q16), and for host builds the first
   quarter of the OP-1's own sine table (the device reads the core's copy in L1).
3. gr_tables.h: note-to-increment steps for the formant model (computed, not from Plaits).
4. wt_tables.h: the wave terrain model: its formulas' divisions as lookup tables over their known ranges (computed from
   Plaits' constants), and Plaits' three integrated wavetable banks, differentiated (the terrains made of wavetables).

    python norn/plugin/gen_tables.py D:/src/mutable-instruments/plaits/resources.cc

Copyright (C) 2026 Jason Bunting. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
The tables are Emilie Gillet's (MIT, see NOTICE).
"""
import math
import re
import sys
from pathlib import Path

SHAPES = ['ws_inverse_tan', 'ws_inverse_sin', 'ws_linear', 'ws_bump', 'ws_double_bump']


def array(src, ctype, name):
    m = re.search(r'const %s lut_%s\[\] = \{(.*?)\};' % (ctype, name), src, re.S)
    if not m:
        sys.exit('gen_tables: lut_%s not found' % name)
    return [float(v.rstrip('f')) for v in re.split(r'[,\s]+', m.group(1).strip()) if v]


def q15(x):
    return max(-32767, min(32767, int(round(x * 32767))))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1]).read_text()
    shapes = [[int(v) for v in array(src, 'int16_t', n)] for n in SHAPES]
    assert all(len(s) == 257 for s in shapes)
    fold = [q15(v) for v in array(src, 'float', 'fold')]
    assert len(fold) == 516

    # ws_fold_at's Hermite terms must stay inside int32 when multiplied by a Q15 fraction
    worst = 0
    for i in range(1, 514):
        xm1, x0, x1, x2 = fold[i - 1], fold[i], fold[i + 1], fold[i + 2]
        c = (x1 - xm1) // 2
        v = x0 - x1
        w = c + v
        a = w + v + (x2 - x0) // 2
        worst = max(worst, abs(a), abs(w + a), abs(c))
    assert worst < 65536, worst

    out = Path(__file__).with_name('ws_tables.h')
    with out.open('w', newline='\n') as f:
        f.write('/* Generated by gen_tables.py from Plaits resources.cc; do not edit. Copyright 2016 Emilie Gillet, MIT\n'
                ' * (see NOTICE). ws_shape: the waveshaper curves, 257 points over -1 .. 1, Q15. ws_fold: the wavefolder,\n'
                ' * 516 points (512 + Hermite guards), Q15. Largest Hermite term: %d. */\n' % worst)
        f.write('#ifndef WS_TABLES_H\n#define WS_TABLES_H\n#include <stdint.h>\n\n')
        f.write('static const int16_t ws_shape[6][257] = {\n')
        for name, s in zip(SHAPES + ['ws_double_bump (sentinel)'], shapes + [shapes[-1]]):
            f.write('  { /* %s */\n' % name)
            for i in range(0, 257, 16):
                f.write('    ' + ', '.join('%d' % v for v in s[i:i + 16]) + ',\n')
            f.write('  },\n')
        f.write('};\n\nstatic const int16_t ws_fold[516] = {\n')
        for i in range(0, 516, 16):
            f.write('  ' + ', '.join('%d' % v for v in fold[i:i + 16]) + ',\n')
        f.write('};\n\n#endif\n')
    print('wrote %s (largest Hermite term %d)' % (out, worst))

    sine = [int(round(32767 * math.sin(2 * math.pi * k / 8192))) for k in range(2049)]   # R246's OP1_SINE_TABLE
    ratio = array(src, 'float', 'fm_frequency_quantizer')
    assert len(ratio) == 130
    mult = [int(round(2 ** (r / 12) * 65536)) for r in ratio]
    out = Path(__file__).with_name('fm_tables.h')
    with out.open('w', newline='\n') as f:
        f.write('/* Generated by gen_tables.py; do not edit. fm_ratio: from Plaits resources.cc (Copyright 2016 Emilie\n'
                ' * Gillet, MIT, see NOTICE), lut_fm_frequency_quantizer (semitones, 129 points over harmonics 0 .. 1,\n'
                ' * + guard) as modulator / carrier frequency, Q16. fm_sine_q: for host builds only (the OP-1 reads the\n'
                ' * core\'s copy in L1), entries 0 .. 2048 of the OP-1\'s sine table, lrint(32767 sin(2 pi k / 8192)). */\n')
        f.write('#ifndef FM_TABLES_H\n#define FM_TABLES_H\n#include <stdint.h>\n\n')
        f.write('static const int16_t fm_sine_q[2049] = {\n')
        for i in range(0, 2049, 16):
            f.write('  ' + ', '.join('%d' % v for v in sine[i:i + 16]) + ',\n')
        f.write('};\n\nstatic const uint32_t fm_ratio[130] = {\n')
        for i in range(0, 130, 8):
            f.write('  ' + ', '.join('%du' % v for v in mult[i:i + 8]) + ',\n')
        f.write('};\n\n#endif\n')
    print('wrote %s' % out)

    # the formant model's frequencies: MIDI notes 0 .. 133 as phase increments at 88.2 kHz, read with linear
    # interpolation between semitones (within 0.7 cent)
    inc = [int(round(440 * 2 ** ((n - 69) / 12) / 88200 * 2 ** 32)) for n in range(134)]
    out = Path(__file__).with_name('gr_tables.h')
    with out.open('w', newline='\n') as f:
        f.write('/* Generated by gen_tables.py; do not edit. gr_note_inc: MIDI notes 0 .. 133 (440 Hz at 69) as phase\n'
                ' * increments at 88.2 kHz (2^32 = one cycle), for the formant model\'s formant frequencies. */\n')
        f.write('#ifndef GR_TABLES_H\n#define GR_TABLES_H\n#include <stdint.h>\n\n')
        f.write('static const uint32_t gr_note_inc[134] = {\n')
        for i in range(0, 134, 6):
            f.write('  ' + ', '.join('%du' % v for v in inc[i:i + 6]) + ',\n')
        f.write('};\n\n#endif\n')
    print('wrote %s' % out)

    # the wave terrain model. Every division in Plaits' terrain formulas has a bounded denominator, so each quotient is
    # a 257-point table over its input's range, read with linear interpolation (wt_lerp). Values are Q15 unless noted.
    def table(fn, lo, hi, n=257, scale=32767):
        vals = [fn(lo + (hi - lo) * i / (n - 1)) for i in range(n)]
        out_ = [int(round(v * scale)) for v in vals]
        assert all(-32767 <= v <= 32767 for v in out_), (fn, max(map(abs, out_)))
        return out_
    squash = lambda s: 2 * s / (1 + abs(2 * s))
    wt = {
        # Squash(Sine(1.273 x), 2) over x in -1 .. 1 (513 points)
        'wt_sq': (table(lambda x: squash(math.sin(2 * math.pi * 1.273 * x)), -1, 1, 513), 'x: -1 .. 1, 513 points'),
        'wt_r1': (table(lambda u: 0.159 / (0.2 + u), 0, 1), '0.159 / (0.2 + u), u: 0 .. 1'),
        'wt_r2': (table(lambda u: 0.159 / (0.35 + u), 0, 1), '0.159 / (0.35 + u), u: 0 .. 1'),
        'wt_r3': (table(lambda w: 6.366 / (2 + 5 * w), 0, 2, scale=4096), '6.366 / (2 + 5 w), w: 0 .. 2, Q12'),
        'wt_r4a': (table(lambda u: 0.159 / (0.17 + u), 0, 2), '0.159 / (0.17 + u), u: 0 .. 2'),
        'wt_r4b': (table(lambda w: 0.477 / (0.35 + w), 0, 4, scale=16384), '0.477 / (0.35 + w), w: 0 .. 4, Q14'),
    }
    for name, (vals, _) in wt.items():
        assert max(abs(vals[i + 1] - vals[i]) for i in range(len(vals) - 1)) < 32768, name
    m = re.search(r'const int16_t wav_integrated_waves\[\] = \{(.*?)\};', src, re.S)
    if not m:
        sys.exit('gen_tables: wav_integrated_waves not found')
    raw = [int(v) for v in re.split(r'[,\s]+', m.group(1).strip()) if v]
    assert len(raw) == 3 * 64 * 132, len(raw)
    # each wave's first differences (Plaits differentiates them on the fly): 130 of them, enough for sample 0 .. 128
    diffs = []
    for w in range(3 * 64):
        row = raw[w * 132:(w + 1) * 132]
        d = [row[k + 1] - row[k] for k in range(130)]
        assert all(abs(v) < 32768 for v in d) and all(abs(d[k + 1] - d[k]) < 32768 for k in range(129))
        diffs.append(d)
    worst = max(abs(v) for d in diffs for v in d)
    out = Path(__file__).with_name('wt_tables.h')
    with out.open('w', newline='\n') as f:
        f.write('/* Generated by gen_tables.py; do not edit. The wave terrain model\'s tables: its formulas\' quotients\n'
                ' * over their inputs\' ranges (257 points unless noted; computed from Plaits\' wave_terrain_engine.cc), and\n'
                ' * wt_waves, Plaits\' wav_integrated_waves (resources.cc, Copyright 2021 Emilie Gillet, MIT; see NOTICE):\n'
                ' * three banks of 64 waves, as the first differences of the integrated data, 1024 = full scale (largest\n'
                ' * %d). */\n' % worst)
        f.write('#ifndef WT_TABLES_H\n#define WT_TABLES_H\n#include <stdint.h>\n\n')
        for name, (vals, note) in wt.items():
            f.write('static const int16_t %s[%d] = {   /* %s */\n' % (name, len(vals), note))
            for i in range(0, len(vals), 16):
                f.write('  ' + ', '.join('%d' % v for v in vals[i:i + 16]) + ',\n')
            f.write('};\n\n')
        f.write('static const int16_t wt_waves[3][64][130] = {\n')
        for b in range(3):
            f.write('  {\n')
            for w in range(64):
                d = diffs[b * 64 + w]
                f.write('    { ' + ', '.join('%d' % v for v in d) + ' },\n')
            f.write('  },\n')
        f.write('};\n\n#endif\n')
    print('wrote %s' % out)


if __name__ == '__main__':
    main()
